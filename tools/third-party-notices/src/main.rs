//! Writes THIRD-PARTY-NOTICES.txt: every Rust crate the Windows app ships, with its licence
//! text, plus the components outside Cargo. `build.ps1` runs this, so the file can't go stale.
//! With `linux` it writes the Linux app's file instead (`packaging/linux/build.sh` runs that).

use serde_json::Value;
use std::collections::{BTreeMap, HashMap, HashSet};
use std::path::{Path, PathBuf};
use std::process::Command;

/// What one build ships: its notices file, Cargo target, the crate whose dependencies
/// ship, and the text about everything outside Cargo.
struct Target {
    out: &'static str,
    platform: &'static str,
    root: &'static str,
    header: &'static str,
}

const WINDOWS: Target = Target { out: "THIRD-PARTY-NOTICES.txt", platform: "x86_64-pc-windows-msvc", root: "mw-engine", header: HEADER };
// The Linux app is the GPUI binary, so its whole dependency tree ships.
const LINUX: Target = Target { out: "packaging/linux/THIRD-PARTY-NOTICES.txt", platform: "x86_64-unknown-linux-gnu", root: "mw-app", header: LINUX_HEADER };

