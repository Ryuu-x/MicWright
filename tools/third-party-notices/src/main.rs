/// Crates reachable from `root` through normal (not build or dev) dependencies.
fn shipped(meta: &Value, root: &str) -> HashSet<String> {
    let nodes: HashMap<&str, &Value> = meta["resolve"]["nodes"].as_array().unwrap().iter().map(|n| (n["id"].as_str().unwrap(), n)).collect();
    let mut seen = HashSet::new();
    let mut todo = vec![root.to_string()];
    while let Some(id) = todo.pop() {
        if !seen.insert(id.clone()) {
            continue;
        }
        for dep in nodes[id.as_str()]["deps"].as_array().unwrap() {
            if dep["dep_kinds"].as_array().unwrap().iter().any(|k| k["kind"].is_null()) {
                todo.push(dep["pkg"].as_str().unwrap().to_string());
            }
        }
    }
    seen
}

fn is_licence_file(path: &Path) -> bool {
    let name = path.file_name().unwrap_or_default().to_string_lossy().to_uppercase();
    path.is_file() && ["LICENSE", "LICENCE", "COPYING", "NOTICE"].iter().any(|p| name.starts_with(p))
}

/// Licence files of a crate. Crates inside a git workspace keep them in a parent folder.
fn licence_files(manifest: &Path) -> Vec<PathBuf> {
    for dir in manifest.ancestors().skip(1).take(2) {
        let mut files: Vec<PathBuf> = std::fs::read_dir(dir).into_iter().flatten().flatten().map(|e| e.path()).filter(|p| is_licence_file(p)).collect();
        if !files.is_empty() {
            files.sort();
            return files;
        }
    }
    Vec::new()
}

fn main() {
    let target = if std::env::args().any(|a| a == "linux") { LINUX } else { WINDOWS };
    let output = Command::new("cargo")
        .args(["metadata", "--format-version", "1", "--locked", "--filter-platform", target.platform])
        .output()
        .expect("run cargo metadata");
    assert!(output.status.success(), "{}", String::from_utf8_lossy(&output.stderr));
    let meta: Value = serde_json::from_slice(&output.stdout).expect("parse cargo metadata");

    let workspace: HashSet<&str> = meta["workspace_members"].as_array().unwrap().iter().map(|m| m.as_str().unwrap()).collect();
    let packages = meta["packages"].as_array().unwrap();
    let root = packages.iter().find(|p| p["name"] == target.root).expect("root crate");
    let ids = shipped(&meta, root["id"].as_str().unwrap());

    let mut crates: Vec<&Value> = packages.iter().filter(|p| ids.contains(p["id"].as_str().unwrap()) && !workspace.contains(p["id"].as_str().unwrap())).collect();
    crates.sort_by_key(|p| (p["name"].as_str().unwrap(), p["version"].as_str().unwrap()));

    let mut listing = String::new();
    // Licence text -> the crates using exactly that text, so shared texts appear once.
    let mut texts: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut without_file = Vec::new();
    for p in &crates {
        let label = format!("{} {}", p["name"].as_str().unwrap(), p["version"].as_str().unwrap());
        listing += &format!("{label:<44} {}\n", p["license"].as_str().unwrap_or("see crate"));
        let files = licence_files(Path::new(p["manifest_path"].as_str().unwrap()));
        if files.is_empty() {
            without_file.push(label.clone());
        }
        for file in files {
            let bytes = std::fs::read(&file).expect("read licence file");
            let text = String::from_utf8_lossy(&bytes).replace("\r\n", "\n").trim().to_string();
            texts.entry(text).or_default().push(label.clone());
        }
    }

    let mut out = target.header.to_string();
    out += &format!("Rust crates ({})\n---------------\n{listing}\n\nLicence texts\n-------------\n", crates.len());
    for (text, users) in &texts {
        out += &format!("\n=== Used by: {}\n\n{text}\n", users.join(", "));
    }
    std::fs::write(target.out, out).expect("write notices");
    println!("{}: {} crates, {} distinct licence texts", target.out, crates.len(), texts.len());
    if !without_file.is_empty() {
        println!("no licence file in the package, listed by licence name only: {}", without_file.join(", "));
    }
}
